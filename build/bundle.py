#!/usr/bin/env python3
"""Bundle src/core.luau + src/modules/*.luau into the single readable src/Polaris.luau.

Each module is wrapped in its own `do ... end` block (own local scope, so the
200-locals-per-function limit is never hit) and receives `Polaris` and `I`
(the internals table) as upvalues.  Modules run in the order listed in
src/modules/ORDER.
"""
import os, sys
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
core = open(os.path.join(root, "src/core.luau")).read()
order = [l.strip() for l in open(os.path.join(root, "src/modules/ORDER")) if l.strip() and not l.startswith("#")]
parts = []
for name in order:
    body = open(os.path.join(root, "src/modules", name)).read()
    parts.append(f"----------------------------------------------------------------\n-- module: {name}\n----------------------------------------------------------------\ndo\n{body}\nend\n")
marker = "--@MODULES@\n"
assert marker in core
out = core.replace(marker, "\n".join(parts))
header = "-- AUTO-GENERATED by build/bundle.py from src/core.luau + src/modules/*.luau. Edit those, not this file.\n"
open(os.path.join(root, "src/Polaris.luau"), "w").write(header + out)
print("bundled", len(order), "modules ->", len(out.splitlines()), "lines")
